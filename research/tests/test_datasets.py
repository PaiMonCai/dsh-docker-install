from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from dsh_research.datasets import (
    dataset_status,
    lineage_tree,
    list_dataset_ids,
    load_dataset_manifest,
    register_dataset,
    verify_catalog,
)
from dsh_research.errors import ManifestError
from dsh_research.project import ResearchProject


class DatasetCatalogTests(unittest.TestCase):
    def make_project(self, root: Path) -> ResearchProject:
        (root / "research.yaml").write_text(
            "schema: 2\nproject:\n  slug: test\n  title: Test\n  template: default\n  status: active\n",
            encoding="utf-8",
        )
        return ResearchProject(root.resolve())

    def test_register_and_verify_dataset(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            project = self.make_project(root)
            (root / "data" / "processed").mkdir(parents=True)
            data = root / "data" / "processed" / "panel.csv"
            data.write_text("id,y\n1,2\n2,3\n", encoding="utf-8")

            path = register_dataset(
                project,
                dataset_id="panel",
                path="data/processed/panel.csv",
                kind="processed",
                title="Panel",
                source="generated by clean.py",
                distributable=True,
            )
            self.assertTrue(path.is_file())
            manifest = load_dataset_manifest(project, "panel")
            self.assertEqual(manifest["dimensions"]["rows"], 2)
            self.assertEqual(manifest["dimensions"]["columns"], 2)
            self.assertEqual(dataset_status(project, "panel").status, "current")
            self.assertEqual(list_dataset_ids(project), ["panel"])

            data.write_text("id,y\n1,99\n2,3\n", encoding="utf-8")
            self.assertEqual(dataset_status(project, "panel").status, "stale")

    def test_manifest_must_stay_inside_project(self) -> None:
        with tempfile.TemporaryDirectory() as td, tempfile.TemporaryDirectory() as outside:
            root = Path(td)
            project = self.make_project(root)
            external = Path(outside) / "secret.csv"
            external.write_text("x\n1\n", encoding="utf-8")
            with self.assertRaises(ManifestError):
                register_dataset(
                    project,
                    dataset_id="outside",
                    path=external,
                    kind="raw",
                )

    def test_lineage_and_missing_dependency(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            project = self.make_project(root)
            (root / "data" / "raw").mkdir(parents=True)
            (root / "data" / "processed").mkdir(parents=True)
            (root / "data" / "raw" / "source.csv").write_text("id\n1\n", encoding="utf-8")
            (root / "data" / "processed" / "panel.csv").write_text("id\n1\n", encoding="utf-8")

            register_dataset(project, dataset_id="source", path="data/raw/source.csv", kind="raw")
            register_dataset(
                project,
                dataset_id="panel",
                path="data/processed/panel.csv",
                kind="processed",
                inputs=["source"],
                pipeline_step="clean",
                run_id="r1",
            )
            tree = lineage_tree(project, "panel")
            self.assertEqual(tree["dataset"], "panel")
            self.assertEqual(tree["inputs"][0]["dataset"], "source")
            self.assertEqual(tree["pipeline_step"], "clean")

            manifest = load_dataset_manifest(project, "panel")
            manifest["lineage"]["inputs"] = [{"dataset": "missing"}]
            from dsh_research.config import write_yaml
            write_yaml(root / "data" / "catalog" / "panel.yaml", manifest)
            failures = [x for x in verify_catalog(project) if x.status != "current"]
            self.assertEqual(len(failures), 1)
            self.assertEqual(failures[0].status, "invalid")

    def test_upstream_change_marks_downstream_stale(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            project = self.make_project(root)
            (root / "data" / "raw").mkdir(parents=True)
            (root / "data" / "processed").mkdir(parents=True)
            source = root / "data" / "raw" / "source.csv"
            panel = root / "data" / "processed" / "panel.csv"
            source.write_text("id,x\n1,2\n", encoding="utf-8")
            panel.write_text("id,y\n1,3\n", encoding="utf-8")

            register_dataset(project, dataset_id="source", path=source, kind="raw")
            register_dataset(
                project,
                dataset_id="panel",
                path=panel,
                kind="processed",
                inputs=["source"],
            )
            self.assertTrue(all(x.status == "current" for x in verify_catalog(project)))

            source.write_text("id,x\n1,99\n", encoding="utf-8")
            register_dataset(
                project,
                dataset_id="source",
                path=source,
                kind="raw",
                force=True,
            )
            statuses = {x.dataset_id: x for x in verify_catalog(project)}
            self.assertEqual(statuses["source"].status, "current")
            self.assertEqual(statuses["panel"].status, "stale")
            self.assertIn("upstream dataset SHA256 changed", statuses["panel"].message)

    def test_transitive_upstream_change_marks_all_downstream_stale(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            project = self.make_project(root)
            (root / "data" / "raw").mkdir(parents=True)
            (root / "data" / "processed").mkdir(parents=True)
            source = root / "data" / "raw" / "source.csv"
            panel = root / "data" / "processed" / "panel.csv"
            analysis = root / "data" / "processed" / "analysis.csv"
            source.write_text("id,x\n1,2\n", encoding="utf-8")
            panel.write_text("id,y\n1,3\n", encoding="utf-8")
            analysis.write_text("id,z\n1,4\n", encoding="utf-8")

            register_dataset(project, dataset_id="source", path=source, kind="raw")
            register_dataset(project, dataset_id="panel", path=panel, kind="processed", inputs=["source"])
            register_dataset(project, dataset_id="analysis", path=analysis, kind="processed", inputs=["panel"])

            source.write_text("id,x\n1,99\n", encoding="utf-8")
            register_dataset(project, dataset_id="source", path=source, kind="raw", force=True)

            statuses = {x.dataset_id: x for x in verify_catalog(project)}
            self.assertEqual(statuses["panel"].status, "stale")
            self.assertEqual(statuses["analysis"].status, "stale")

    def test_code_change_marks_dataset_stale(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            project = self.make_project(root)
            (root / "data" / "processed").mkdir(parents=True)
            (root / "src").mkdir()
            data = root / "data" / "processed" / "panel.csv"
            code = root / "src" / "clean.py"
            data.write_text("id,y\n1,3\n", encoding="utf-8")
            code.write_text("print('v1')\n", encoding="utf-8")
            register_dataset(
                project,
                dataset_id="panel",
                path=data,
                kind="processed",
                code=["src/clean.py"],
            )
            code.write_text("print('v2')\n", encoding="utf-8")
            status = {x.dataset_id: x for x in verify_catalog(project)}["panel"]
            self.assertEqual(status.status, "stale")
            self.assertIn("lineage code SHA256 changed", status.message)

    def test_force_required_to_update_manifest(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            project = self.make_project(root)
            (root / "data" / "processed").mkdir(parents=True)
            path = root / "data" / "processed" / "x.csv"
            path.write_text("x\n1\n", encoding="utf-8")
            register_dataset(project, dataset_id="x", path=path, kind="processed")
            with self.assertRaises(ManifestError):
                register_dataset(project, dataset_id="x", path=path, kind="processed")
            path.write_text("x\n2\n", encoding="utf-8")
            register_dataset(project, dataset_id="x", path=path, kind="processed", force=True)
            self.assertEqual(dataset_status(project, "x").status, "current")


if __name__ == "__main__":
    unittest.main()
